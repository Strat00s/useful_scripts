def resolve_passphrase(args):
    """
    Return (description, env_updates). The secret itself only goes into `env`.

    Precedence: --password, --password-file, $<--password-env>,
    --password-command, $BORG_PASSCOMMAND, interactive prompt.
    """
    if args.password is not None:
        return ("--password on the command line (visible in `ps`; prefer "
                "--password-file)", {"BORG_PASSPHRASE": args.password})

    if args.password_file:
        try:
            with open(args.password_file, encoding="utf-8") as handle:
                secret = handle.readline().rstrip("\r\n")
        except OSError as exc:
            fail(f"cannot read password file {args.password_file}: {exc}")
        return (f"--password-file {args.password_file}",
                {"BORG_PASSPHRASE": secret})

    if args.password_env in os.environ:
        return (f"environment ${args.password_env}",
                {"BORG_PASSPHRASE": os.environ[args.password_env]})

    if args.password_command:
        return (f"--password-command {args.password_command}",
                {"BORG_PASSCOMMAND": args.password_command})

    if "BORG_PASSCOMMAND" in os.environ:
        return ("environment $BORG_PASSCOMMAND", {})

    if sys.stdin.isatty():
        return ("interactive prompt",
                {"BORG_PASSPHRASE": getpass.getpass(
                    "Repository passphrase (empty if the repo has none): ")})

    return ("none provided — borg will prompt on the terminal or fail", {})


