KEEP_OPTIONS = ("keep-within", "keep-last", "keep-secondly", "keep-minutely",
                "keep-hourly", "keep-daily", "keep-weekly", "keep-monthly",
                "keep-yearly")

# The openmediavault borgbackup job this script replaces.
DEFAULT_RETENTION = {"keep-weekly": 4, "keep-monthly": 3}


def resolve_retention(args):
    """Explicit --keep-* wins; otherwise the OMV defaults are used."""
    given = {}
    for option in KEEP_OPTIONS:
        value = getattr(args, option.replace("-", "_"), None)
        if value is not None:
            given[option] = value
    if given:
        return given, False
    return dict(DEFAULT_RETENTION), True


class Borg:
    """Builds borg command lines for the installed borg major version."""

    def __init__(self, major):
        self.major = major
        # Differences that matter here (probed, not assumed): borg 2 takes the
        # archive as a positional instead of repository::archive, spells
        # --glob-archives as --match-archives, and has no compact --threshold.
        self.show_rc = supports("create", "--show-rc")
        self.stats = supports("create", "--stats")
        self.list_flag = "--list" if supports("create", "--list") else None
        if supports("prune", "--glob-archives"):
            self.archives_filter = "--glob-archives"
            self.archives_prefix = ""
        else:
            self.archives_filter = "--match-archives"
            self.archives_prefix = "sh:"

    def archive_glob(self, pattern):
        return self.archives_prefix + pattern

    def init_mode(self, args):
        return args.encryption or ("repokey-blake2-aes-ocb" if self.major >= 2
                                   else "repokey-blake2")

    def init(self, args):
        verb = "repo-create" if self.major >= 2 else "init"
        return [BORG_BIN, verb, "--encryption", self.init_mode(args)]

    def create(self, args, archive, sources):
        cmd = [BORG_BIN, "create", "--verbose"]
        if args.dry_run:
            cmd += ["--dry-run"]
        if args.list_files and self.list_flag:
            cmd += [self.list_flag]
            if args.filter and supports("create", "--filter"):
                cmd += ["--filter", args.filter]
        if self.stats and not args.dry_run:
            # a dry run has nothing to report statistics about
            cmd += ["--stats"]
        if self.show_rc and args.show_rc:
            cmd += ["--show-rc"]
        cmd += ["--compression", args.compression]
        if args.exclude_caches:
            cmd += ["--exclude-caches"]
        for pattern in args.exclude:
            cmd += ["--exclude", pattern]
        for path in args.exclude_from:
            cmd += ["--exclude-from", path]
        if args.create_args:
            cmd += shlex.split(args.create_args)
        # borg 1.x: "repository::archive" (repository comes from BORG_REPO);
        # borg 2: the archive name is the first positional argument.
        cmd.append(archive if self.major >= 2 else "::" + archive)
        return cmd + list(sources)

    def prune(self, args, prefix, retention):
        cmd = [BORG_BIN, "prune"]
        if args.list_files and self.list_flag:
            cmd += [self.list_flag]
        for option in KEEP_OPTIONS:
            if option in retention:
                cmd += [f"--{option}", str(retention[option])]
        if self.show_rc and args.show_rc:
            cmd += ["--show-rc"]
        cmd += [self.archives_filter, self.archive_glob(f"{prefix}-*")]
        if args.dry_run:
            cmd += ["--dry-run"]
        return cmd

    def compact(self, args):
        cmd = [BORG_BIN, "compact", "--verbose"]
        if supports("compact", "--threshold"):
            cmd += ["--threshold", str(args.compact_threshold)]
        return cmd

    def check(self, args, archive):
        cmd = [BORG_BIN, "check", "--verbose"]
        if supports("check", "--archives-only"):
            cmd += ["--archives-only"]
        if supports("check", "--glob-archives"):
            cmd += ["--glob-archives", archive]
        elif supports("check", "--match-archives"):
            cmd += ["--match-archives", "sh:" + archive]
        return cmd

    def list_archives(self, count):
        # borg 2 lists a repository's archives with the repo-list command; its
        # plain "list" needs an archive name and lists that archive's contents.
        cmd = [BORG_BIN, "repo-list" if self.major >= 2 else "list"]
        verb = cmd[1]
        if supports(verb, "--last"):
            cmd += ["--last", str(count)]
        if self.major < 2 and supports(verb, "--short"):
            # borg 2's repo-list --short prints bare ids; its default format
            # (id, timestamp, name, user, host) is what is worth seeing.
            cmd += ["--short"]
        return cmd


