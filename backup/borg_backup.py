# Parsing borg's statistics block
# ---------------------------------------------------------------------------

SIZE_UNITS = {"B": 1, "KB": 1000, "MB": 1000 ** 2, "GB": 1000 ** 3,
              "TB": 1000 ** 4, "PB": 1000 ** 5,
              "KIB": 1024, "MIB": 1024 ** 2, "GIB": 1024 ** 3,
              "TIB": 1024 ** 4, "PIB": 1024 ** 5}


def parse_size(text):
    """'22.88 GB' -> bytes, matching borg's 1000-based unit reporting."""
    text = (text or "").strip()
    match = re.match(r"^([\d.,]+)\s*([A-Za-z]*)(?:i?B)?$", text)
    if not match:
        return None
    value = float(match.group(1).replace(",", ""))
    unit = (match.group(2) or "B").upper()
    if unit == "":
        unit = "B"
    if unit not in SIZE_UNITS:
        return None
    return value * SIZE_UNITS[unit]


SIZES_RE = re.compile(r"([\d.,]+)\s*([A-Za-z]{1,2}B?)")


def split_sizes(text):
    """'3.20 MB 3.00 MB 3.00 MB' -> ['3.20 MB', '3.00 MB', '3.00 MB']."""
    pairs = SIZES_RE.findall(text or "")
    return [f"{value} {unit.strip()}" for value, unit in pairs[:3]]


def parse_duration(text):
    """'8 minutes 40.52 seconds' -> 520.52; also accepts 'H:MM:SS.aa'."""
    text = (text or "").strip()
    if not text:
        return None
    multipliers = {"day": 86400, "hour": 3600, "minute": 60, "second": 1}
    total = 0.0
    found = False
    for value, unit in re.findall(r"([\d.]+)\s*(days?|hours?|minutes?|seconds?)",
                                  text, re.I):
        total += float(value) * multipliers[unit.lower().rstrip("s")]
        found = True
    if found:
        return total
    parts = text.split(":")
    if len(parts) == 3:
        try:
            return int(parts[0]) * 3600 + int(parts[1]) * 60 + float(parts[2])
        except ValueError:
            return None
    return None


# borg --list prints one status character per item ("A /path", "U /path", …)
ITEM_LINE = re.compile(r"^[A-Za-z><]\s")

# borg 1.x writes progress chatter, the --list items, the statistics block and
# the actual problem to the *same* stream. Everything matching this is not
# interesting in the report; what is left over becomes a message when a phase
# fails. Patterns are from observed `borg create/prune/compact/check --verbose`
# output (borg 1.4) plus argparse's usage dump.
_BORING = [
    r"^\s",                       # indented: traceback or argparse continuation
    r"^[A-Za-z><]\s",              # --list item line
    r"^-{5,}$",                    # statistics block separator
    r"^\[?-{1,2}\w",               # argparse option dump: "[-h]", "--stats SPEC"
    r"^usage:",                    # argparse usage banner
    r"\[PATH ",                    # argparse parameter line
    r"^(Original size|Unique chunks)\s\s",  # statistics column headers (1.x)
    r"^(Original|Compressed|Deduplicated) size$",
    r"^Creating (archive at|repository)",
    r"^Initializing repository",
    r"^Synchronizing chunks cache",
    r"^Archives: \d+, ",
    r"^(Fetching and building|Reading cached) archive",
    r"^Merging into master chunks index",
    r"^Building master chunks index",
    r"^Done\.?$",
    r"^Determining archives to clean up",
    r"^(Keeping|Pruning) archive",
    r"^Would (remove|prune) ",
    r"^Would have been removed",
    r"^Starting archive consistency check",
    r"^(Analyzing|Verifying) ",
    r"^Orphaned objects check skipped",
    r"^Archive consistency check complete",
    r"^Remote: Warning: Permanently added",          # ssh host-key chatter
    r"^(Added|Unchanged|Modified|Error) files:",      # borg 2 stats fields
    r"^Files changed while reading:",
    r"^Bytes (read from|sent to) remote:",
    r"^Time spent in \w+:",
    r"^compaction freed",
    r"^check_free_space",
    r"^Using security path",
    r"^using service cmdline",
    r"^Lock: ",
    r"^(Waiting on|Acquired) lock",
    r"^Trying to create exclusive lock",
    r"^Detaching after fork",
    r"^Initializing cache transaction",
    r"^Saving (files|chunks) cache",
    r"^Saving cache config",
    r"^Generating a new key",
    r"^storing key for repo id",
    r"^Security directory",
    r"^(Platform|Linux|Borg|PID|sys\.argv|SSH_ORIGINAL_COMMAND):",
]
BORING = re.compile("|".join(f"(?:{pattern})" for pattern in _BORING))


class Stats:
    """Everything interesting from one borg phase's output."""

    FIELDS = (
        ("repository", r"^Repository:\s+(.+)$"),
        ("archive", r"^Archive name:\s+(.+)$"),
        ("fingerprint", r"^Archive (?:fingerprint|id):\s+(.+)$"),
        ("start", r"^Time \(start\):\s+(.+)$"),
        ("end", r"^Time \(end\):\s+(.+)$"),
        ("duration_text", r"^Duration:\s+(.+)$"),
        ("files", r"^Number of files:\s+([\d,.]+)$"),
        ("utilization", r"^Utilization of max\. archive size:\s+(\d+)"),
        ("chunk_index", r"^Chunk index:\s+([\d,.]+)\s+([\d,.]+)$"),
        ("this_archive", r"^(?:This archive|Archive):\s+(.+)$"),
        ("all_archives", r"^All archives:\s+(.+)$"),
        # borg 2 has no size triple; it reports these flat fields instead
        ("original", r"^Original size:\s+(.+)$"),
        ("compressed", r"^Compressed size:\s+(.+)$"),
        ("deduplicated", r"^Deduplicated size:\s+(.+)$"),
    )

    def __init__(self):
        self.repository = None
        self.archive = None
        self.fingerprint = None
        self.start = None
        self.end = None
        self.duration_text = None
        self.files = None
        self.utilization = None
        self.chunk_index = None
        self.this_archive = None
        self.all_archives = None
        self.original = self.compressed = self.deduplicated = None
        self.warnings = []
        self.errors = []
        # lines that matched nothing (become messages when the phase failed)
        self.plain = []

    def feed(self, raw_line):
        line = raw_line.strip()
        if not line:
            return
        for name, pattern in self.FIELDS:
            match = re.search(pattern, line)
            if not match:
                continue
            if name == "chunk_index":
                self.chunk_index = tuple(match.groups())
            elif name in ("this_archive", "all_archives"):
                setattr(self, name, split_sizes(match.group(1)))
            else:
                setattr(self, name, match.group(1))
            return

        if re.match(r"^(Warning|WARNING):", line):
            self.warnings.append(re.sub(r"^(Warning|WARNING):\s*", "", line))
        elif re.match(r"^(ERROR|Error):", line):
            self.errors.append(re.sub(r"^(ERROR|Error):\s*", "", line))
        elif line.startswith(("Command Error:", "Local Exception",
                              "borg: error:", "Traceback (most recent call")):
            self.errors.append(line)
        elif not BORING.match(raw_line):
            # borg mixes progress chatter, usage dumps and the real problem on
            # the same stream; keep the lines that are neither, in case the
            # phase ends up failing (see phase_messages).
            self.plain.append(line)

    def size(self, which, index):
        triple = getattr(self, which)
        if not triple or index >= len(triple):
            return None
        return parse_size(triple[index])

    def dedup_bytes(self):
        """New data in this archive; both borg stats layouts are read."""
        value = self.size("this_archive", 2)
        if value is None and self.deduplicated:
            value = parse_size(self.deduplicated)
        return value

    def sizes_summary(self):
        """The size line, from borg 1.x's triple or borg 2's flat fields."""
        if self.this_archive:
            names = ("original", "compressed", "deduplicated")
            return "  ".join(f"{name} {value}"
                             for name, value in zip(names, self.this_archive))
        pairs = (("original", self.original), ("compressed", self.compressed),
                 ("deduplicated", self.deduplicated))
        return "  ".join(f"{name} {value}"
                         for name, value in pairs if value) or "-"

    @property
    def duration(self):
        return parse_duration(self.duration_text)

    @property
    def complete(self):
        return bool(self.archive or self.files or self.this_archive
                    or self.deduplicated)


