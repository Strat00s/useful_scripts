#!/usr/bin/env python3
"""
Borg Backup Runner — runs `borg create` for a set of paths against a repository
(on another machine over SSH, or local), then prunes, optionally compacts and
verifies, and prints a report saying what was backed up, where, how long it
took, and whether the whole run succeeded.

Modelled on the scripts generated by the openmediavault borgbackup plugin, so a
job can be moved here without changing behaviour:

  * `borg create --verbose --filter AME --list --stats --show-rc
     --compression auto,lzma,9 --exclude-caches ::<prefix>-<timestamp>`
  * `borg prune --list --glob-archives '<prefix>-*' --keep-weekly 4 --keep-monthly 3`
  * `borg compact --verbose --threshold 10`
  * `BORG_EXIT_CODES=modern`, `BORG_LOCK_WAIT` default 3600
  * one flock per repository so two runs never fight over the repository lock
  * exit-code classes identical to the plugin: 0 ok, 1 warning, 2..99 error,
    100..127 warning, >=128 killed by a signal. The worst phase decides the
    overall status, which becomes this script's exit status (0 ok, 1 warnings,
    2 failure, 4 repository busy).
  * `--init` runs `borg init` / `borg2 repo-create` when borg reports that the
    repository does not exist — borg >= 1.2 refuses to create one by itself,
    and the plugin generates an `init` step for the same reason.

The passphrase only ever reaches borg through the environment
(BORG_PASSPHRASE / BORG_PASSCOMMAND) and is redacted everywhere else.

Requirements: `borg` 1.x (the borg 2 command line is detected and adapted),
source paths readable by the running user, SSH key access for user@host:/path
repositories.
"""

