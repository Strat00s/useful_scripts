def redact(text):
    """Never let a passphrase reach the terminal, the log, or an exception."""
    text = re.sub(r"(BORG_PASSPHRASE=)\S+", r"\1<redacted>", text)
    return re.sub(r"(--passphrase[ =])\S+", r"\1<redacted>", text)


class Runner:
    """Runs borg phases, streams their output, and records everything."""

    def __init__(self, env, log_file, quiet):
        self.env = env
        self.log_file = log_file
        self.quiet = quiet
        self.phases = []
        self._log = None
        if log_file:
            try:
                self._log = open(log_file, "a", encoding="utf-8")
            except OSError as exc:
                log_line(f"Warning: cannot append to {log_file}: {exc}",
                         stream=sys.stderr)

    def write_log(self, text):
        if self._log:
            try:
                self._log.write(text)
                self._log.flush()
            except OSError as exc:
                log_line(f"Warning: log file write failed ({exc}); continuing "
                         f"without a log.", stream=sys.stderr)
                try:
                    self._log.close()
                except OSError:
                    pass
                self._log = None

    def close(self):
        if self._log:
            try:
                self._log.close()
            except OSError:
                pass
            self._log = None

    def run(self, name, argv):
        printable = redact(" ".join(shlex.quote(a) for a in argv))
        log_line(f"{name}: {printable}")
        self.write_log(f"\n{time.strftime('%F %T')} {name}: {printable}\n")

        started = time.monotonic()
        process = subprocess.Popen(
            argv, env=self.env, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, text=True, errors="replace", bufsize=1,
        )

        stats = Stats()
        counters = {"added": 0, "changed": 0}
        for raw in process.stdout:
            line = raw.rstrip("\n").rstrip("\r")
            stats.feed(line)
            self.write_log(line + "\n")
            if not self.quiet:
                print(line, flush=True)
            # borg item lines: A = archived (new), M = modified
            if ITEM_LINE.match(line) and line[0] in "AM":
                counters["added" if line[0] == "A" else "changed"] += 1

        rc = process.wait()
        elapsed = time.monotonic() - started
        cls = rc_class(rc)
        log_line(f"{name} finished in {human_duration(elapsed)}: "
                 f"{colorize(rc_label(rc), STATUS_COLOR[cls])}")
        self.write_log(f"{name}: rc={rc} ({cls}) in {elapsed:.2f}s\n")
        self.phases.append({
            "name": name, "rc": rc, "class": cls, "elapsed": elapsed,
            "stats": stats, "argv": printable, "counters": counters,
        })
        return self.phases[-1]


# ---------------------------------------------------------------------------
# Repository lock (one lock per repository, like the OMV plugin)
# ---------------------------------------------------------------------------

def acquire_lock(repo, wait, enabled):
    """Returns a lock handle, None when disabled, or 'timeout'."""
    if not enabled:
        return None
    repo_id = hashlib.sha256(repo.encode()).hexdigest()[:16]
    for directory in ("/run/lock", "/var/tmp", "/tmp"):
        try:
            os.makedirs(directory, exist_ok=True)
            path = os.path.join(directory, f"borg-backup-{repo_id}.lock")
            handle = open(path, "w")
        except OSError:
            continue
        deadline = time.monotonic() + max(0, wait)
        log_line(f"Waiting for repo lock ({wait}s): {path}")
        while True:
            try:
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
                log_line(f"Acquired repo lock: {path}")
                return handle
            except OSError as exc:
                if exc.errno not in (errno.EACCES, errno.EAGAIN):
                    handle.close()
                    raise
                if time.monotonic() >= deadline:
                    handle.close()
                    log_line(f"Failed to acquire repo lock after {wait}s: {path}",
                             stream=sys.stderr)
                    return "timeout"
                time.sleep(1)
    log_line("Warning: no writable lock directory; running without a lock.",
             stream=sys.stderr)
    return None


