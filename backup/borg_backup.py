def build_parser():
    epilog = (
        "examples:\n"
        "  # a job on another box, repository over ssh:\n"
        "  borg_backup.py -r borg@backup-server:/srv/pool/borg \\\n"
        "      --password-file /root/.config/borg/vm_images.pw -n vm_images \\\n"
        "      /srv/pool/vms\n\n"
        "  # local repository, tighter retention, only the summary on stdout:\n"
        "  BORG_PASSPHRASE=secret borg_backup.py -r /backup/repo -q \\\n"
        "      --keep-daily 7 --keep-monthly 6 /etc /root\n\n"
        "  # first run: borg will not create a repository, so ask for it:\n"
        "  borg_backup.py -r /backup/repo --init --keep-daily 7 /etc\n\n"
        "  # see what would be archived and pruned, write nothing:\n"
        "  borg_backup.py -r /backup/repo --dry-run /var/log\n"
    )
    p = argparse.ArgumentParser(
        prog="borg_backup.py",
        description="Run a borg backup (create + prune + compact) and report "
                    "what was archived, where, how long it took, and whether "
                    "the run succeeded.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=epilog,
    )
    p.add_argument("sources", nargs="+", metavar="PATH",
                   help="files or directories to back up")

    conn = p.add_argument_group("repository")
    conn.add_argument("-r", "--repo", default=os.environ.get("BORG_REPO"),
                      metavar="REPO",
                      help="borg repository: user@host:/path, "
                           "ssh://user@host/path or a local path "
                           "(default: $BORG_REPO)")
    conn.add_argument("--password", metavar="PASSPHRASE", default=None,
                      help="repository passphrase; visible in `ps`, so prefer "
                           "--password-file or $BORG_PASSPHRASE")
    conn.add_argument("--password-file", metavar="FILE",
                      help="read the passphrase from the first line of FILE")
    conn.add_argument("--password-env", metavar="NAME", default="BORG_PASSPHRASE",
                      help="environment variable holding the passphrase "
                           "(default: %(default)s)")
    conn.add_argument("--password-command", metavar="CMD",
                      help="command that prints the passphrase (BORG_PASSCOMMAND)")
    conn.add_argument("--rsh", default=os.environ.get("BORG_RSH"), metavar="CMD",
                      help="ssh command for remote repositories (BORG_RSH), "
                           "e.g. 'ssh -i /root/.ssh/borg -p 22'")

    arc = p.add_argument_group("archive contents")
    arc.add_argument("-n", "--name", metavar="PREFIX",
                     help="archive prefix; the archive is <PREFIX>-<timestamp> "
                          "(default: hostname)")
    arc.add_argument("--compression", default="auto,lzma,9", metavar="SPEC",
                     help="borg compression specification (default: %(default)s)")
    arc.add_argument("--filter", default="AME", metavar="STATUSCHARS",
                     help="only list items with these borg status characters, "
                           "A=added M=modified E=new attributes; pass '' to "
                           "list unchanged items too (default: %(default)s)")
    arc.add_argument("--no-list", dest="list_files", action="store_false",
                     help="do not list archived items, only print the report")
    arc.add_argument("--exclude", action="append", default=[], metavar="PATTERN",
                     help="exclude a shell pattern (repeatable)")
    arc.add_argument("--exclude-from", action="append", default=[], metavar="FILE",
                     help="read exclude patterns from a file (repeatable)")
    arc.add_argument("--no-exclude-caches", dest="exclude_caches",
                     action="store_false",
                     help="do not skip directories marked with CACHEDIR.TAG")
    arc.add_argument("--create-args", default="", metavar="ARGS",
                     help="extra raw arguments for borg create, e.g. "
                          "--create-args='--one-file-system --numeric-owner'")

    ret = p.add_argument_group(
        "retention",
        "pruning happens after a successful create and only touches archives "
        "named <PREFIX>-*; with no --keep-* options the openmediavault job "
        "defaults (keep-weekly 4, keep-monthly 3) are used")
    for option in KEEP_OPTIONS:
        ret.add_argument("--" + option, dest=option.replace("-", "_"),
                         type=int, metavar="N", default=None,
                         help=f"keep {option[5:]} archives")
    ret.add_argument("--no-prune", action="store_true",
                     help="skip the prune phase entirely")
    ret.add_argument("--no-compact", action="store_true",
                     help="skip the compact phase")
    ret.add_argument("--compact-threshold", type=int, default=10, metavar="PCT",
                     help="compact repositories with less than this percent "
                          "free (default: %(default)s)")

    run = p.add_argument_group("run control")
    run.add_argument("--borg", default="borg", metavar="PATH",
                     help="borg executable to run (default: %(default)s; "
                          "Debian's borgbackup2 package ships it as borg2)")
    run.add_argument("--dry-run", action="store_true",
                     help="create and prune with --dry-run: nothing is written "
                          "(borg also disables --stats, so no size statistics)")
    run.add_argument("--verify", action="store_true",
                     help="afterwards run 'borg check' on the new archive")
    run.add_argument("--init", action="store_true",
                     help="if borg reports that the repository does not exist "
                          "or is not initialized, initialize it and retry "
                          "(borg does that by itself only for a path that does "
                          "not exist yet — an existing empty directory is "
                          "rejected)")
    run.add_argument("--encryption", metavar="MODE",
                     help="encryption mode for --init (default: "
                          "repokey-blake2 on borg 1.x, "
                          "repokey-blake2-aes-ocb on borg 2)")
    run.add_argument("--show-archives", type=int, default=0, metavar="N",
                     help="also list the N newest archives of the repository")
    run.add_argument("--log-file", metavar="FILE",
                     help="append full borg output to FILE "
                          "(default: /var/log/borgbackup/<PREFIX>.log)")
    run.add_argument("--no-log", dest="log", action="store_false",
                     help="do not write a log file")
    run.add_argument("--lock-wait", type=int,
                     default=int(os.environ.get("BORG_LOCK_WAIT", 3600)),
                     metavar="SECONDS",
                     help="how long to wait for this repository's lock "
                          "(default: 3600, $BORG_LOCK_WAIT)")
    run.add_argument("--no-lock", dest="lock", action="store_false",
                     help="do not serialize runs against this repository")
    run.add_argument("--keep-env", action="store_true",
                     help="do not set BORG_EXIT_CODES/BORG_LOCK_WAIT ourselves")
    run.add_argument("--show-rc", action="store_true",
                     help="ask borg to print its own 'exit code: N' line")
    run.add_argument("-q", "--quiet", action="store_true",
                     help="hide borg's own output; print only the report")
    run.add_argument("-c", "--color", action="store_true",
                     help="force ANSI colors even when stdout is not a terminal "
                          "(piped / redirected output)")
    p._optionals.title = "help"
    return p


