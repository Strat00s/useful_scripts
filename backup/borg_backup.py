# Debian coinstalls borgbackup (/usr/bin/borg, 1.x) and borgbackup2
# (/usr/bin/borg2, 2.x), so the binary is an option: --borg.
BORG_BIN = "borg"


def borg_version():
    res = subprocess.run([BORG_BIN, "--version"], capture_output=True, text=True)
    if res.returncode != 0:
        return "", 0
    match = re.search(r"(\d+)\.(\d+)", res.stdout or "")
    if not match:
        return (res.stdout or "").strip(), 0
    return match.group(0), int(match.group(1))


_HELP_CACHE = {}


def help_text(verb):
    if verb not in _HELP_CACHE:
        res = subprocess.run([BORG_BIN, verb, "--help"],
                             capture_output=True, text=True)
        _HELP_CACHE[verb] = (res.stdout or "") + (res.stderr or "")
    return _HELP_CACHE[verb]


def supports(verb, flag):
    """Whether this borg build knows FLAG for the given verb."""
    return re.search(re.escape(flag) + r"(?![\w-])", help_text(verb)) is not None


