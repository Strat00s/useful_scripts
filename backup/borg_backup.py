def rc_class(rc):
    if rc == 0:
        return "ok"
    if rc == 1:
        return "warn"
    if 2 <= rc <= 99:
        return "err"
    if 100 <= rc <= 127:
        return "warn"
    if rc >= 128:
        return "sig"
    return "err"


def signal_name(rc):
    try:
        return signal_module.Signals(rc - 128).name
    except (ValueError, OSError):
        return f"signal {rc - 128}"


def rc_label(rc):
    cls = rc_class(rc)
    if cls == "ok":
        return "ok"
    if cls == "sig":
        return f"killed: {signal_name(rc)}"
    kind = "warning" if cls == "warn" else "error"
    meaning = RC_MEANING.get(rc) or RC_GENERIC.get(rc)
    if meaning:
        return f"{kind}({rc}: {meaning})"
    return f"{kind}({rc})"


