# Main
# ---------------------------------------------------------------------------

def main():
    args = build_parser().parse_args()
    configure_color(True if args.color else None)

    global BORG_BIN
    BORG_BIN = args.borg
    if shutil.which(BORG_BIN) is None:
        fail(f"'{BORG_BIN}' is not installed or not in PATH "
             f"(apt install borgbackup, or borgbackup2 for /usr/bin/borg2)")

    if not args.repo:
        fail("no repository given: pass -r/--repo or set $BORG_REPO")

    missing = [s for s in args.sources if not os.path.exists(s)]
    if missing:
        fail("source path(s) do not exist: " + ", ".join(missing))

    if args.no_prune and any(getattr(args, o.replace("-", "_"), None) is not None
                             for o in KEEP_OPTIONS):
        fail("--no-prune cannot be combined with --keep-* options")

    version, major = borg_version()
    if not major:
        fail("could not determine the borg version")
    borg = Borg(major)
    retention, defaulted = resolve_retention(args)

    repo = args.repo
    prefix = args.name or os.uname().nodename
    archive = f"{prefix}-{time.strftime('%Y-%m-%d_%H-%M-%S')}"

    passphrase_desc, secret_env = resolve_passphrase(args)

    env = os.environ.copy()
    env["BORG_REPO"] = repo
    env.setdefault("LC_ALL", "C.UTF-8")
    env.update(secret_env)
    if args.rsh:
        env["BORG_RSH"] = args.rsh
    if not args.keep_env:
        env.setdefault("BORG_LOCK_WAIT", str(args.lock_wait))
        if major < 2:
            env.setdefault("BORG_EXIT_CODES", "modern")

    log_file = args.log_file or f"/var/log/borgbackup/{prefix}.log"
    if not args.log:
        log_file = None
    elif log_file:
        directory = os.path.dirname(log_file)
        try:
            if directory:
                os.makedirs(directory, exist_ok=True)
            with open(log_file, "a", encoding="utf-8") as handle:
                handle.write(f"\n{'=' * 78}\n"
                             f"{time.strftime('%F %T')} borg_backup.py "
                             f"{archive}\nrepository: {repo}\n")
        except OSError as exc:
            print(colorize(f"Warning: cannot use log file {log_file}: {exc}",
                           Colors.WARNING), file=sys.stderr)
            log_file = None

    runner = Runner(env, log_file, args.quiet)

    print()
    print(colorize("BORG BACKUP", Colors.HEADER + Colors.BOLD))
    rows = []
    if args.dry_run:
        rows.append(["mode", colorize("DRY RUN — nothing is written",
                                      Colors.WARNING + Colors.BOLD)])
    rows += [
        ["borg", f"{version} ({BORG_BIN})"],
        ["repository", repo],
        ["archive", archive],
        ["sources", ", ".join(args.sources)],
        ["compression", args.compression],
        ["prune", prune_summary(args, borg, prefix, retention, defaulted)],
        ["compact", "disabled" if (args.no_compact or args.dry_run)
         else f"yes (--threshold {args.compact_threshold})"],
        ["verify", "yes (borg check)" if args.verify else "no"],
        ["init", f"yes, if the repository is missing "
                 f"({borg.init_mode(args)})" if args.init
         else "no — borg will not create a missing repository"],
        ["lock", f"yes, waiting up to {args.lock_wait}s" if args.lock else "no"],
        ["log file", log_file or "none"],
    ]
    print_table(["", "SETTING"], rows, max_widths=[14, 100])

    lock = acquire_lock(repo, args.lock_wait, args.lock)
    if lock == "timeout":
        runner.close()
        fail(f"repository {repo} is busy (lock not acquired in "
             f"{args.lock_wait}s)", code=4)

    interrupted = False
    try:
        create = runner.run("create", borg.create(args, archive, args.sources))
        if args.init and create["rc"] in (13, 15):
            # borg initializes a repository by itself only when its path does
            # not exist at all; an existing (empty) directory is refused, so
            # initialize it here and retry. The failed attempt stays in the
            # phase table but must not decide the verdict.
            create["recoverable"] = True
            runner.run("init", borg.init(args))
            create = runner.run("create",
                                borg.create(args, archive, args.sources))
        if rc_class(create["rc"]) in ("ok", "warn"):
            if not args.no_prune:
                runner.run("prune", borg.prune(args, prefix, retention))
            if not args.no_compact and not args.dry_run:
                runner.run("compact", borg.compact(args))
            if args.verify and not args.dry_run:
                runner.run("verify", borg.check(args, archive))
            if args.show_archives and not args.dry_run:
                runner.run("archives",
                           borg.list_archives(args.show_archives))
    except KeyboardInterrupt:
        interrupted = True
        log_line("Interrupted — borg was terminated.", stream=sys.stderr)
    finally:
        if lock not in (None, "timeout"):
            fcntl.flock(lock, fcntl.LOCK_UN)
            lock.close()

    try:
        code = report(runner, args, borg, archive, repo, interrupted)
    finally:
        if log_file:
            runner.write_log(f"\noverall exit status: {code}\n")
            print(f"Log: {log_file}")
        runner.close()
    return code


def prune_summary(args, borg, prefix, retention, defaulted):
    if args.no_prune:
        return "disabled (--no-prune)"
    spec = ", ".join(f"--{option} {value}"
                     for option, value in retention.items())
    note = " [OMV defaults]" if defaulted else ""
    return f"{spec}{note} on {borg.archives_filter} " \
           f"{borg.archive_glob(f'{prefix}-*')}"


RANK = {"ok": 0, "warn": 1, "err": 2, "sig": 3}


def report(runner, args, borg, archive, repo, interrupted):
    """Print the report and return the exit status for the whole run."""
    if not runner.phases:
        print(colorize("Nothing ran.", Colors.WARNING))
        return 2

    creates = [phase for phase in runner.phases if phase["name"] == "create"]
    create = creates[-1] if creates else runner.phases[0]
    stats = create["stats"]
    overall = "sig" if interrupted else max(
        (p["class"] for p in runner.phases if not p.get("recoverable")),
        key=lambda cls: RANK[cls])
    total_elapsed = sum(p["elapsed"] for p in runner.phases)

    print()
    print(colorize("PHASES", Colors.HEADER + Colors.BOLD))
    rows = []
    for phase in runner.phases:
        label = rc_label(phase["rc"])
        if phase.get("recoverable"):
            label += " → retried"
        rows.append([
            phase["name"],
            colorize(label, STATUS_COLOR[phase["class"]]),
            f"{phase['counters']['added']} added / "
            f"{phase['counters']['changed']} changed"
            if phase["name"] == "create" and (args.list_files or
                                              phase["counters"]["added"]) else "",
            human_duration(phase["elapsed"]),
        ])
    rows.append([colorize("total", Colors.BOLD), "", "",
                 colorize(human_duration(total_elapsed), Colors.BOLD)])
    headers = ["PHASE", "RESULT", "ITEMS", "DURATION"]
    if not any(row[2] for row in rows[:-1]):
        headers[2] = ""
    print_table(headers, rows)

    print()
    print(colorize("ARCHIVE", Colors.HEADER + Colors.BOLD))
    new_bytes = stats.dedup_bytes()
    # borg's own duration excludes the repository handshake and cache
    # synchronisation, so the throughput figure describes the actual transfer
    create_secs = stats.duration or create["elapsed"]
    rate = (new_bytes / create_secs) if (new_bytes and create_secs > 0) else None

    if not stats.complete:
        rows = [["statistics", "none reported by borg"
                 + (" (dry runs report no sizes)" if args.dry_run else "")],
                ["wall time", human_duration(create_secs)]]
    else:
        rows = [
            ["repository", stats.repository or repo],
            ["archive", stats.archive or archive],
            ["fingerprint", stats.fingerprint or "-"],
            ["started", stats.start or "-"],
            ["finished", stats.end or "-"],
            ["duration", stats.duration_text or human_duration(create_secs)],
            ["files", stats.files or "-"],
            ["this archive", stats.sizes_summary()],
            ["new data", human_bytes(new_bytes) if new_bytes else "-"],
            ["throughput", f"{human_bytes(rate)}/s" if rate else "-"],
        ]
        if stats.all_archives:
            rows.append(["all archives", "  ".join(
                f"{name} {value}" for name, value in
                zip(("original", "compressed", "deduplicated"),
                    stats.all_archives))])
        if stats.chunk_index:
            rows.append(["chunks", f"{stats.chunk_index[0]} unique / "
                                   f"{stats.chunk_index[1]} total"])
        if args.dry_run:
            rows.insert(0, ["mode", "dry run — no archive was written"])
    print_table(["", "VALUE"], rows, max_widths=[14, 100])

    messages = []
    for phase in runner.phases:
        for level, text in phase_messages(phase):
            messages.append((phase["name"], level, text))

    if messages:
        print()
        print(colorize(f"MESSAGES ({len(messages)})", Colors.WARNING + Colors.BOLD))
        for phase, level, text in messages[:25]:
            color = {"ERROR": Colors.FAIL, "warning": Colors.WARNING,
                     "output": Colors.DIM}[level]
            print(f"  {colorize(f'{level:<7}', color)} [{phase}] {fit(text, 112)}")
        if len(messages) > 25:
            print(colorize(f"  … {len(messages) - 25} more in the log file",
                           Colors.DIM))

    print()
    verdict, color, summary = verdict_for(overall, runner, interrupted, stats,
                                          new_bytes, rate, create_secs, archive)
    print(colorize(verdict, color + Colors.BOLD),
          colorize(summary, Colors.DIM))
    print()
    return {"ok": 0, "warn": 1}.get(overall, 2)


def phase_messages(phase):
    """
    The human-useful lines of one phase.

    Errors and warnings are always shown. A phase that did not exit 0 also
    contributes its leftover output (already filtered by BORING in Stats.feed),
    because borg writes the actual reason as a bare line — "passphrase supplied
    in BORG_PASSPHRASE … is incorrect", for instance.
    """
    stats = phase["stats"]
    out = [("ERROR", text) for text in stats.errors]
    out += [("warning", text) for text in stats.warnings]
    if phase["rc"] != 0:
        out += [("output", text) for text in stats.plain[-6:]]
    return out


def verdict_for(overall, runner, interrupted, stats, new_bytes, rate,
                create_secs, archive):
    if interrupted:
        return ("FAILED", Colors.FAIL,
                "interrupted by the user (borg was terminated)")

    failed = [p for p in runner.phases if p["class"] in ("err", "sig")
              and not p.get("recoverable")]
    if failed:
        detail = ", ".join(f"{p['name']}={rc_label(p['rc'])}" for p in failed)
        # borg writes its own reason last, after any chatter
        lines = [text for level, text in phase_messages(failed[0])
                 if level in ("ERROR", "output")]
        hint = f" — {lines[-1]}" if lines else ""
        if any(p["rc"] in (13, 15) for p in failed):
            hint += "  (create it first: --init)"
        return ("FAILED", Colors.FAIL, f"{detail}{hint}")

    counts = stats.files
    volume = f", {human_bytes(new_bytes)} new" if new_bytes else ""
    speed = f", {human_bytes(rate)}/s" if rate else ""
    what = f"{counts} files" if counts else "no statistics"
    timing = human_duration(create_secs)
    warn = [p["name"] for p in runner.phases if p["class"] == "warn"]
    if warn:
        return ("SUCCESS (WITH WARNINGS)", Colors.WARNING,
                f"{what} → {archive} in {timing}{volume} — "
                f"warnings in: {', '.join(warn)}")
    return ("SUCCESS", Colors.OKGREEN, f"{what} → {archive} in {timing}{volume}{speed}")


if __name__ == "__main__":
    raise SystemExit(main())
