ANSI_ESCAPE = re.compile(r"\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])")


class Colors:
    HEADER = "\033[95m"
    OKBLUE = "\033[94m"
    OKCYAN = "\033[96m"
    OKGREEN = "\033[92m"
    WARNING = "\033[93m"
    FAIL = "\033[91m"
    ENDC = "\033[0m"
    BOLD = "\033[1m"
    DIM = "\033[2m"


USE_COLOR = sys.stdout.isatty()


def configure_color(force=None):
    """
    Resolve whether ANSI color codes are emitted.

    By default colors follow tty detection (stdout piped/redirected -> plain).
    `force=True` overrides that and emits colors anyway (used by --color);
    `force=False` suppresses them; `force=None` leaves the detected value
    untouched. Returns the resulting setting.
    """
    global USE_COLOR
    if force is not None:
        USE_COLOR = bool(force)
    return USE_COLOR


def colorize(text, color_code):
    if USE_COLOR:
        return f"{color_code}{text}{Colors.ENDC}"
    return text


def visible_len(text):
    return len(ANSI_ESCAPE.sub("", str(text)))


def fit(text, width):
    text = str(text)
    if visible_len(text) <= width:
        return text
    out = []
    used = 0
    i = 0
    while i < len(text):
        if text.startswith("\x1b", i):
            match = ANSI_ESCAPE.match(text, i)
            if match:
                out.append(match.group(0))
                i = match.end()
                continue
        if used >= width - 1:
            break
        out.append(text[i])
        used += 1
        i += 1
    out.append("…")
    if ANSI_ESCAPE.search("".join(out)):
        out.append(Colors.ENDC)
    return "".join(out)


def print_table(headers, rows, max_widths=None):
    widths = [len(h) for h in headers]
    for row in rows:
        for i, value in enumerate(row):
            widths[i] = max(widths[i], visible_len(value))
    if max_widths:
        widths = [min(w, m) for w, m in zip(widths, max_widths)]

    print("│".join(fit(h, w).center(w) for h, w in zip(headers, widths)))
    print("├".join("─" * w for w in widths))
    for row in rows:
        cells = []
        for i, value in enumerate(row):
            pad = max(0, widths[i] - visible_len(value))
            cells.append(fit(value, widths[i]) + " " * pad)
        print("│".join(cells))


def human_bytes(value):
    if value is None:
        return "-"
    value = float(value)
    if value < 1000:
        return f"{value:.0f} B"
    units = ["kB", "MB", "GB", "TB", "PB", "EB"]
    n = -1
    while value >= 1000 and n < len(units) - 1:
        value /= 1000.0
        n += 1
    return f"{value:.2f} {units[n]}"


def human_duration(seconds):
    if seconds is None:
        return "-"
    seconds = int(seconds)
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    if hours:
        return f"{hours}h{minutes:02d}m{secs:02d}s"
    if minutes:
        return f"{minutes}m{secs:02d}s"
    return f"{secs}s"


def stamp():
    return time.strftime("%H:%M:%S")


def log_line(text, stream=sys.stdout):
    print(f"[{stamp()}] {text}", file=stream, flush=True)


def fail(message, code=2):
    print(colorize(f"Error: {message}", Colors.FAIL + Colors.BOLD),
          file=sys.stderr)
    sys.exit(code)


